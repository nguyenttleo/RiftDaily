export function championSplashPosition(champion: ChampionSplashPositionInput, mode: ChampionSplashPositionMode = "default") {
  const keys =
    typeof champion === "string"
      ? [champion]
      : [champion.id, champion.name, champion.label];

  for (const key of keys) {
    if (!key) {
      continue;
    }

    const normalizedKey = normalizeChampionSplashKey(key);
    const position = CHAMPION_SPLASH_POSITIONS[normalizedKey];

    if (position) {
      return mode === "portrait" ? (CHAMPION_SPLASH_PORTRAIT_POSITIONS[normalizedKey] ?? toPortraitSplashPosition(position)) : position;
    }
  }

  return mode === "portrait" ? DEFAULT_CHAMPION_SPLASH_PORTRAIT_POSITION : DEFAULT_CHAMPION_SPLASH_POSITION;
}

export function normalizeChampionSplashKey(value: string) {
  return value.replace(/[^a-z0-9]/gi, "").toLowerCase();
}

function toPortraitSplashPosition(position: string) {
  const match = position.match(/^(\d+(?:\.\d+)?)%\s+(\d+(?:\.\d+)?)%$/);

  if (!match) {
    return DEFAULT_CHAMPION_SPLASH_PORTRAIT_POSITION;
  }

  const [, xRaw, yRaw] = match;
  const x = Number(xRaw);
  const y = Number(yRaw);

  if (!Number.isFinite(x) || !Number.isFinite(y)) {
    return DEFAULT_CHAMPION_SPLASH_PORTRAIT_POSITION;
  }

  return `${Math.min(86, Math.max(64, x + 24))}% ${y}%`;
}
